<?php
namespace Opencart\Catalog\Model\Pms;

class Settings extends \Opencart\System\Engine\Model {

    private $settings_cache = [];
    private $cache_time = 3600; // 1 hour
    private $cache_file = 'pms_settings.php';

    /**
     * Get all settings with aggressive caching
     */
    public function getAll(): array {
        // Check memory cache first
        if (!empty($this->settings_cache)) {
            return $this->settings_cache;
        }

        // Check session cache
        $cache_key = 'pms_settings_all';
        if (isset($this->session->data['pms_settings_cache'][$cache_key])) {
            $cached = $this->session->data['pms_settings_cache'][$cache_key];
            if ($cached['expires'] > time()) {
                $this->settings_cache = $cached['data'];
                return $this->settings_cache;
            }
        }

        // Check file-based cache (persistent across sessions)
        $file_cache = DIR_CACHE . $this->cache_file;
        if (file_exists($file_cache) && (filemtime($file_cache) > (time() - $this->cache_time))) {
            $cached_data = include $file_cache;
            if (is_array($cached_data)) {
                $this->settings_cache = $cached_data;
                // Also store in session
                $this->session->data['pms_settings_cache'][$cache_key] = [
                    'data' => $cached_data,
                    'expires' => time() + $this->cache_time
                ];
                return $this->settings_cache;
            }
        }

        // Query database (only if not cached)
        $query = $this->db->query("
            SELECT `key`, value 
            FROM `" . DB_PREFIX . "setting`
        ");

        $settings = [];
        foreach ($query->rows as $row) {
            $settings[$row['key']] = $row['value'];
        }

        // Store in all caches
        $this->settings_cache = $settings;
        
        // Session cache
        $this->session->data['pms_settings_cache'][$cache_key] = [
            'data' => $settings,
            'expires' => time() + $this->cache_time
        ];

        // File cache
        $this->writeFileCache($settings);

        return $settings;
    }

    /**
     * Write settings to file cache
     */
    private function writeFileCache(array $settings): void {
        $file = DIR_CACHE . $this->cache_file;
        $content = '<?php' . "\n";
        $content .= '// PMS Settings Cache - Generated ' . date('Y-m-d H:i:s') . "\n";
        $content .= '// Do not edit this file manually' . "\n\n";
        $content .= 'return ' . var_export($settings, true) . ';';
        
        file_put_contents($file, $content);
    }

    /**
     * Get a single setting value
     */
    public function get(string $key): string {
        $settings = $this->getAll();
        return $settings[$key] ?? '';
    }

    /**
     * Get manager group ID
     */
    public function getManagerGroupId(): int {
        return (int)$this->get('manager_group_id');
    }

    /**
     * Get accountant group ID
     */
    public function getAccountantGroupId(): int {
        return (int)$this->get('accountant_group_id');
    }

    /**
     * Get shareholder group ID
     */
    public function getShareholderGroupId(): int {
        return (int)$this->get('shareholder_group_id');
    }

    /**
     * Clear all caches
     */
    public function clearCache(): void {
        // Clear session cache
        unset($this->session->data['pms_settings_cache']);
        $this->settings_cache = [];
        
        // Clear file cache
        $file = DIR_CACHE . $this->cache_file;
        if (file_exists($file)) {
            unlink($file);
        }
    }
}